// Generates src/lib/tax-sources.gen.ts from seo-build/data/tax-sources.json, the
// single source of truth for the tax rates the Loan Copilot shows and for the
// sources of the Tax Agent's gain tax / holding exemption / filing cards. Only the
// fields the modules need are copied (no quotes/notes in the bundle). It also fails
// if the English texts in src/lib/tax.ts (COUNTRY_TAX) differ from
// fields.<field>.text in the JSON. Runs before every
// `npm run build` (and in CI), so a rate change in the JSON reaches the module on
// the next build.
//   node scripts/gen-tax-sources.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const srcPath = join(here, '../../seo-build/data/tax-sources.json');
const outPath = join(here, '../src/lib/tax-sources.gen.ts');
const data = JSON.parse(readFileSync(srcPath, 'utf8'));
if (!Array.isArray(data.countries)) throw new Error('tax-sources.json: "countries" array missing');

const countries = data.countries.map((c) => {
  if (typeof c.id !== 'string') throw new Error('tax-sources.json: country without id');
  const rate = c.loanRate === null || c.loanRate === undefined ? null : Number(c.loanRate);
  if (rate !== null && !(Number.isFinite(rate) && rate >= 0 && rate <= 1)) {
    throw new Error(`tax-sources.json: ${c.id} loanRate ${c.loanRate} is not a decimal between 0 and 1`);
  }
  return {
    id: c.id,
    name: String(c.name ?? c.id),
    loanRate: rate,
    condition: String(c.condition ?? ''),
    source: String(c.source ?? ''),
    verified: c.verified === true,
  };
});

// ── Tax Agent: per-field sources + text check ──────────────────
const FIELDS = ['gainTax', 'exemption', 'filing'];
const fieldsChecked = String(data.fieldsChecked ?? '');
if (!/^\d{4}-\d{2}-\d{2}$/.test(fieldsChecked)) throw new Error(`tax-sources.json: fieldsChecked "${fieldsChecked}" is not YYYY-MM-DD`);
const fieldSources = {};
for (const c of data.countries) {
  const f = c.fields || {};
  const row = {};
  for (const k of FIELDS) {
    const src = typeof f[k]?.source === 'string' ? f[k].source : '';
    if (src && !/^https:\/\//.test(src)) throw new Error(`tax-sources.json: ${c.id}.fields.${k}.source is not an https URL`);
    row[k] = { source: src, checked: fieldsChecked };
  }
  fieldSources[c.id] = row;
}

// English in tax.ts must match fields.<f>.text, ignoring "%" spacing and "19–35" vs "19 to 35".
const norm = (x) => String(x)
  .replace(/[  ]/g, ' ')
  .replace(/(\d)\s?%/g, '$1%')
  .replace(/(\d)\s*[–—-]\s*(\d)/g, '$1 to $2')
  .replace(/\s+/g, ' ')
  .trim();
const taxTs = readFileSync(join(here, '../src/lib/tax.ts'), 'utf8');
const listStart = taxTs.indexOf('export const COUNTRY_TAX');
const listEnd = taxTs.indexOf('\n];', listStart);
if (listStart < 0 || listEnd < 0) throw new Error('tax.ts: COUNTRY_TAX not found');
const list = taxTs.slice(listStart, listEnd);
const blocks = list.split(/\n  \{\n/).slice(1);
const mismatches = [];
const seen = new Set();
for (const b of blocks) {
  const id = (b.match(/id: '([a-z]+)'/) || [])[1];
  if (!id) continue;
  seen.add(id);
  const src = data.countries.find((c) => c.id === id);
  if (!src) { mismatches.push(`${id}: not in tax-sources.json`); continue; }
  for (const k of FIELDS) {
    const m = b.match(new RegExp(`\\b${k}: \\{ en: ('(?:\\\\.|[^'\\\\])*'|"(?:\\\\.|[^"\\\\])*")`));
    if (!m) { mismatches.push(`${id}.${k}: English text not found in tax.ts`); continue; }
    // eslint-disable-next-line no-new-func
    const en = Function(`"use strict";return ${m[1]}`)();
    const want = src.fields?.[k]?.text;
    if (typeof want !== 'string') { mismatches.push(`${id}.${k}: no fields.${k}.text in tax-sources.json`); continue; }
    if (norm(en) !== norm(want)) mismatches.push(`${id}.${k}:\n    tax.ts: ${en}\n    json  : ${want}`);
  }
}
if (seen.size === 0) throw new Error('tax.ts: no countries parsed from COUNTRY_TAX');
if (mismatches.length) {
  throw new Error(`tax.ts COUNTRY_TAX differs from tax-sources.json fields.<field>.text:\n  ${mismatches.join('\n  ')}`);
}

const body = `// GENERATED by scripts/gen-tax-sources.mjs from seo-build/data/tax-sources.json. Do not edit.
export interface TaxSourceRow {
  id: string;
  name: string;
  loanRate: number | null;
  condition: string;
  source: string;
  verified: boolean;
}

export const TAX_SOURCES: { checked: string; countries: TaxSourceRow[] } = ${JSON.stringify({ checked: String(data.checked ?? ''), countries }, null, 2)};

// Tax Agent: official source per card (gain tax / holding exemption / filing).
// checked = fieldsChecked (YYYY-MM-DD). An empty source means "no source".
export type TaxField = 'gainTax' | 'exemption' | 'filing';
export interface TaxFieldSource {
  source: string;
  checked: string;
}

export const TAX_FIELD_SOURCES: { checked: string; countries: Record<string, Record<TaxField, TaxFieldSource>> } = ${JSON.stringify({ checked: fieldsChecked, countries: fieldSources }, null, 2)};
`;
writeFileSync(outPath, body);
const shown = countries.filter((c) => c.verified && c.loanRate !== null).map((c) => `${c.id} ${Math.round(c.loanRate * 1000) / 10}%`);
console.log(`Tax sources OK (${data.checked}): ${shown.length ? shown.join(', ') : 'no verified country, only Custom rate'}`);
const full = Object.entries(fieldSources).filter(([, r]) => FIELDS.every((k) => r[k].source)).map(([id]) => id);
console.log(`Tax Agent field sources (${fieldsChecked}): ${full.length}/${Object.keys(fieldSources).length} countries with all three sources; tax.ts texts match`);
