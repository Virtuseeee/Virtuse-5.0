// Third build step (npm run build): the Partner Finder strings of a module
// dictionary as a small plain-JS file for Verdict's result page
// (pf-dict-<lang>.js, global VBPartnersDict[lang]). Only the entries whose
// English key appears in concierge.ts, so the page never downloads the other
// modules' text. Add a language to LANGS when its Verdict page exists.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LANGS = ['ru'];
const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(here, '..', 'src', 'lib');
const SITE = path.join(here, '..', '..', 'Kimi_Agent_Virtuse%20MiCA%20Partners');
const source = readFileSync(path.join(SRC, 'concierge.ts'), 'utf8').replace(/\\'/g, "'");

for (const lang of LANGS) {
  const ts = readFileSync(path.join(SRC, 'i18n', `${lang}.ts`), 'utf8');
  const body = ts.slice(ts.indexOf('{'), ts.lastIndexOf('}') + 1);
  const dict = JSON.parse(body.replace(/,\s*}$/, '}'));
  const used = Object.fromEntries(Object.entries(dict).filter(([en]) => source.includes(en)));
  writeFileSync(path.join(SITE, `pf-dict-${lang}.js`),
    `// Generated by layer2-src/scripts/gen-pf-dicts.mjs from src/lib/i18n/${lang}.ts. Do not edit by hand.\n` +
    `(window.VBPartnersDict = window.VBPartnersDict || {})[${JSON.stringify(lang)}] = ${JSON.stringify(used)};\n`);
  console.log(`pf-dict-${lang}.js: ${Object.keys(used).length} of ${Object.keys(dict).length} strings`);
}
