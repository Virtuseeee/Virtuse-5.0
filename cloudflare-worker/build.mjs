#!/usr/bin/env node
// Generates the data modules the Worker imports, all in src/generated/:
//
//   checklists.js        <- Kimi_Agent_Virtuse%20MiCA%20Partners/data/partner-checklists.json   (committed)
//   tax-facts.js         <- seo-build/data/seo-data.json + meta.json                         (committed)
//   waitlist-strings.js  <- email/waitlist-strings.json + seo-build/data/footer-operator.json (committed)
//   welcome-templates.js <- email/welcome-template*.html                                     (git-ignored)
//   build-info.js        <- BUILD_COMMIT env, else git HEAD (+ "-dirty")                     (git-ignored)
//
// The committed ones are committed so tests and reviews see the same data the
// deploy ships; deploy_worker.sh fails if checklists.js is out of date.
// Wrangler bundles src/index.js directly (wrangler.toml `main`); nothing is
// patched into the source any more.
//
// Run before tests, dev and deploy (the npm scripts do):
//   node build.mjs && npx wrangler deploy

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const GENERATED = path.join(__dirname, 'src', 'generated');
mkdirSync(GENERATED, { recursive: true });

const module = (from, value) =>
  `// Generated by build.mjs from ${from}. Do not edit by hand.\nexport default ${JSON.stringify(value, null, 1)};\n`;

// Partner registration steps for POST /send kind "checklist": the site's
// data/partner-checklists.json becomes src/generated/checklists.js (committed, so the
// tests and wrangler's bundler see the same data).
const CHECKLISTS_JSON = path.join(ROOT, 'Kimi_Agent_Virtuse%20MiCA%20Partners', 'data', 'partner-checklists.json');
const checklists = existsSync(CHECKLISTS_JSON) ? JSON.parse(readFileSync(CHECKLISTS_JSON, 'utf8')).partners : {};
writeFileSync(
  path.join(GENERATED, 'checklists.js'),
  '// Generated by build.mjs from data/partner-checklists.json. Do not edit by hand.\n' +
    'export default ' + JSON.stringify(checklists, null, 1) + ';\n'
);

// Tax facts for POST /verdict: the 13 countries of the Tax & Inheritance
// Agent, from the same seo-build/data/seo-data.json the tax pages use, so
// Verdict never states a rule the site doesn't. Committed like checklists.js.
const SEO_DATA = path.join(ROOT, 'seo-build', 'data', 'seo-data.json');
if (existsSync(SEO_DATA)) {
  const seo = JSON.parse(readFileSync(SEO_DATA, 'utf8'));
  // Slovak wording of the same facts (seo-build meta.json taxSk), for the
  // one-line country rule in the result (verdict-result-v2 §4).
  const META = path.join(ROOT, 'seo-build', 'data', 'meta.json');
  const meta = existsSync(META) ? JSON.parse(readFileSync(META, 'utf8')) : {};
  const taxSk = meta.taxSk || {};
  // Russian wording (meta.json taxRu, same text as the ru/ tax pages) for the ru Verdict.
  const taxRu = meta.taxRu || {};
  const short = (t) => t ? { gainTax: t.gainTax, ...(t.healthLevyShort ? { healthLevyShort: t.healthLevyShort } : {}), exemption: t.exemption } : null;
  const countries = seo.countries.map(({ id, name, gainTax, healthLevy, exemption, note }) => {
    const sk = short(taxSk[id]);
    const ru = short(taxRu[id]);
    return { id, name, gainTax, ...(healthLevy ? { healthLevy } : {}), exemption, note,
      ...(sk ? { sk } : {}), ...(ru ? { ru } : {}) };
  });
  writeFileSync(
    path.join(GENERATED, 'tax-facts.js'),
    '// Generated by build.mjs from seo-build/data/seo-data.json. Do not edit by hand.\n' +
      'export default ' + JSON.stringify({ asOf: seo.asOf, countries }, null, 1) + ';\n'
  );
}

// Waitlist confirmation email texts (POST /waitlist), 10 languages, plus the operator
// line in each language from the site's footer (same text as on every page).
const WAITLIST_JSON = path.join(ROOT, 'email', 'waitlist-strings.json');
const OPERATOR_JSON = path.join(ROOT, 'seo-build', 'data', 'footer-operator.json');
if (existsSync(WAITLIST_JSON) && existsSync(OPERATOR_JSON)) {
  const strings = JSON.parse(readFileSync(WAITLIST_JSON, 'utf8'));
  const op = JSON.parse(readFileSync(OPERATOR_JSON, 'utf8'));
  const out = {};
  for (const [lang, t] of Object.entries(strings)) {
    if (lang.startsWith('_')) continue;
    if (!op[lang]) throw new Error('footer-operator.json has no ' + lang);
    out[lang] = { ...t, operator: op[lang].label + op[lang].text };
  }
  writeFileSync(
    path.join(GENERATED, 'waitlist-strings.js'),
    '// Generated by build.mjs from email/waitlist-strings.json + seo-build/data/footer-operator.json. Do not edit by hand.\n' +
      'export default ' + JSON.stringify(out, null, 1) + ';\n'
  );
}

// Brief welcome emails, lang -> HTML. Add a row (and a row in
// src/features/newsletter/welcome.js) when a language gets its own template --
// see README.md's "Multi-language welcome emails" section.
const WELCOME_TEMPLATES = { en: 'welcome-template.html', sk: 'welcome-template-sk.html' };
const welcome = {};
for (const [lang, file] of Object.entries(WELCOME_TEMPLATES)) {
  welcome[lang] = readFileSync(path.join(ROOT, 'email', file), 'utf8');
}
writeFileSync(path.join(GENERATED, 'welcome-templates.js'), module('email/welcome-template*.html', welcome));

// Commit stamp for GET /version: BUILD_COMMIT env, else git HEAD (+ "-dirty"
// when the Worker or email folders have uncommitted changes).
let commit = process.env.BUILD_COMMIT || 'unknown';
if (!process.env.BUILD_COMMIT) {
  try {
    commit = execSync('git rev-parse HEAD', { cwd: __dirname }).toString().trim();
    const dirty = execSync('git status --porcelain -- . ../email', { cwd: __dirname }).toString().trim();
    if (dirty) commit += '-dirty';
  } catch { /* not a git checkout */ }
}
writeFileSync(
  path.join(GENERATED, 'build-info.js'),
  '// Generated by build.mjs. Do not edit by hand.\nexport const BUILD_COMMIT = ' + JSON.stringify(commit) + ';\n'
);

console.log('Built src/generated/ (commit ' + commit + ')');
