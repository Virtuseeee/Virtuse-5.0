#!/usr/bin/env python3
"""Export the v2 site chrome for the seo-build pages (checklist 2.2).

usage: python3 i18n-tools/seo_chrome.py          write seo-build/data/chrome-v2.json
       python3 i18n-tools/seo_chrome.py --check  exit 1 if the JSON is out of date

seo-build (Node) renders ~200 guide pages (tax guides, buy-bitcoin/<country>, DCA,
sell vs borrow, inheritance, DAC8) in 10 languages. Their nav, footer and Brief card
come from this JSON, so they match the v2 pages built in Python:
  nav / foot  the language homepage's v2 header and footer (same code as the Fee
              Index builder), links made root-absolute ("/de/...") so they work at
              any folder depth. Language-menu links are "{{ALT:xx}}" placeholders;
              html.mjs fills them with the page's own hreflang alternates.
  brief       the v2 Brief card (latest issue + signup, source "seo_page").
  i18n        window.VB_I18N strings for site-v2.js (empty for EN).
Re-run after a homepage nav/footer change or a new Brief issue, then run
`node seo-build/generate.mjs` (CI regenerates from the committed JSON).
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'fee-index'))
import build_fee_index as F

OUT = os.path.join(F.DATA, 'chrome-v2.json')


def placeholders(nav, foot):
    def langs(seg):
        def one(m):
            tag = m.group(0)
            x = re.search(r'hreflang="([a-z]{2})"', tag).group(1)
            return re.sub(r'href="[^"]*"', 'href="{{ALT:%s}}"' % x, tag, count=1)
        return re.sub(r'<a [^>]*hreflang="[a-z]{2}"[^>]*>', one, seg)

    def apply(html, start):
        i = html.index(start)
        j = html.index('</nav>' if start.startswith('<nav') else '</div>', i)
        return html[:i] + langs(html[i:j]) + html[j:]
    return apply(nav, '<div class="lang-menu-panel"'), apply(foot, '<nav class="footer-langs"')


def build():
    data = {'_note': 'Generated by i18n-tools/seo_chrome.py from the v2 homepages. Do not edit by hand.'}
    for L in F.LANGS:
        nav, foot = F.chrome(L, lambda x: '/')
        nav, foot = placeholders(nav, foot)
        t = json.load(open(os.path.join(F.TOOLS, 'bots', L + '.json')))
        brief = F.brief_card(L, t, source='seo_page')
        i18n = F.i18n_script(L).strip()
        for part in (nav, foot, brief):
            assert '{' not in part.replace('{{ALT:', ''), (L, 'unfilled placeholder')
        data[L] = {'nav': nav, 'foot': foot, 'brief': brief, 'i18n': i18n}
    return json.dumps(data, ensure_ascii=False, indent=1) + '\n'


def main():
    out = build()
    if '--check' in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != out:
            sys.exit('seo-build/data/chrome-v2.json is out of date: run python3 i18n-tools/seo_chrome.py')
        print('chrome-v2.json up to date')
        return
    open(OUT, 'w').write(out)
    print('wrote', os.path.relpath(OUT, F.REPO), len(out), 'bytes')


if __name__ == '__main__':
    main()
