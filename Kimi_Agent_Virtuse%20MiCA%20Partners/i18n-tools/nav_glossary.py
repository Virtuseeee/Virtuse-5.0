#!/usr/bin/env python3
"""Bitcoin glossary in the Learn menu and the footer Guides column, EN and SK only (SEO Bod E).

The glossary exists in English (/bitcoin-glossary/) and Slovak (/sk/bitcoin-slovnik/). On every page
that carries the v2 menu:
  Learn menu   after "Country tax guides" / "Daňové návody podľa krajín":
               EN "Bitcoin glossary · {n} terms: EU rules, tax, macro", SK "Bitcoin slovník · {n} pojmov: ..."
  footer       after "Inheritance" / "Dedenie" in the Guides column.
The other 8 languages get no link (no translation yet); a glossary link that reaches one of their
pages (copied from the English homepage by a builder) is removed again.

csp_tight.tighten() calls apply(), so a page rebuild keeps the links.
  python3 nav_glossary.py            patch every built page + seo-build/data/chrome-v2.json
  python3 nav_glossary.py --check    exit 1 if anything would change
{n} comes from seo-build/data/glossary.json (number of terms).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
REPO = os.path.dirname(SITE)
GLOSSARY = os.path.join(REPO, 'seo-build', 'data', 'glossary.json')
CHROME = os.path.join(REPO, 'seo-build', 'data', 'chrome-v2.json')


def _n():
    with open(GLOSSARY, encoding='utf-8') as f:
        return len(json.load(f)['terms'])


N = _n()
HREF = {'en': '/bitcoin-glossary/', 'sk': '/sk/bitcoin-slovnik/'}
NAV_ANCHOR = {
    'en': '<a href="/bitcoin-tax/"><span class="nd-t">Country tax guides</span><span class="nd-d">Tax rules in 13 EU countries</span></a>',
    'sk': '<a href="/sk/bitcoin-dane/"><span class="nd-t">Daňové návody podľa krajín</span><span class="nd-d">Daňové pravidlá v 13 krajinách EÚ</span></a>',
}
NAV_ITEM = {
    'en': '<a href="/bitcoin-glossary/"><span class="nd-t">Bitcoin glossary</span><span class="nd-d">%d terms: EU rules, tax, macro</span></a>' % N,
    'sk': '<a href="/sk/bitcoin-slovnik/"><span class="nd-t">Bitcoin slovník</span><span class="nd-d">%d pojmov: pravidlá EÚ, dane, makro</span></a>' % N,
}
FOOT_ANCHOR = {'en': '<a href="/bitcoin-inheritance/">Inheritance</a>', 'sk': '<a href="/sk/bitcoin-dedicstvo/">Dedenie</a>'}
FOOT_ITEM = {'en': '<a href="/bitcoin-glossary/">Bitcoin glossary</a>', 'sk': '<a href="/sk/bitcoin-slovnik/">Bitcoin slovník</a>'}
# Any glossary link in a menu or footer (old {n}, other language), to put it back exactly once.
NAV_ANY = re.compile(r'<a href="/(?:sk/bitcoin-slovnik|bitcoin-glossary)/"(?: aria-current="page")?><span class="nd-t">[^<]*</span><span class="nd-d">[^<]*</span></a>')
FOOT_ANY = re.compile(r'<a href="/(?:sk/bitcoin-slovnik|bitcoin-glossary)/">Bitcoin (?:glossary|slovník)</a>')
LANG_RE = re.compile(r'<html lang="([a-z]{2})"')


def patch(html, lang):
    """Menu + footer links for this page's language (en/sk), none elsewhere. Idempotent."""
    html = NAV_ANY.sub('', html)
    html = FOOT_ANY.sub('', html)
    if lang in HREF:
        if NAV_ANCHOR[lang] in html:
            html = html.replace(NAV_ANCHOR[lang], NAV_ANCHOR[lang] + NAV_ITEM[lang])
        if FOOT_ANCHOR[lang] in html:
            html = html.replace(FOOT_ANCHOR[lang], FOOT_ANCHOR[lang] + FOOT_ITEM[lang])
    return html


def apply(html, page_path=None):
    # The glossary pages are built by seo-build/glossary.mjs, which marks its own menu item as current.
    if 'generated by seo-build/glossary.mjs' in html:
        return html
    m = LANG_RE.search(html)
    if not m:
        return html
    return patch(html, m.group(1))


def pages():
    for root, dirs, files in os.walk(SITE):
        dirs[:] = [d for d in dirs if d not in ('i18n-tools', 'node_modules', 'research', 'partnerships')]
        for f in files:
            if f.endswith('.html'):
                yield os.path.join(root, f)


def run(check):
    changed = []
    for p in pages():
        with open(p, encoding='utf-8', newline='') as f:
            s = f.read()
        if 'bitcoin-glossary' not in s and 'Country tax guides' not in s and 'Daňové návody podľa krajín' not in s \
                and 'bitcoin-inheritance/">Inheritance' not in s and 'bitcoin-dedicstvo/">Dedenie' not in s:
            continue
        t = apply(s, p)
        if t != s:
            changed.append(os.path.relpath(p, SITE))
            if not check:
                with open(p, 'w', encoding='utf-8', newline='') as f:
                    f.write(t)
    with open(CHROME, encoding='utf-8') as f:
        c = json.load(f)
    c2 = json.loads(json.dumps(c))
    for L in c2:
        if isinstance(c2[L], dict) and 'nav' in c2[L]:
            c2[L]['nav'] = patch(c2[L]['nav'], L)
            c2[L]['foot'] = patch(c2[L]['foot'], L)
    if c2 != c:
        changed.append('seo-build/data/chrome-v2.json')
        if not check:
            with open(CHROME, 'w', encoding='utf-8') as f:
                f.write(json.dumps(c2, ensure_ascii=False, indent=1) + '\n')  # same format as seo_chrome.py
    return changed


if __name__ == '__main__':
    check = '--check' in sys.argv
    ch = run(check)
    print('%s %d file(s)' % ('would change' if check else 'changed', len(ch)))
    for x in ch[:20]:
        print('  ' + x)
    sys.exit(1 if (check and ch) else 0)
