#!/usr/bin/env python3
"""Ecosystem as the 4th menu group (after Services, Learn, Tools) and an Ecosystem footer column.

One-off, idempotent. Texts come from seo-build/data/ecosystem-strings/<lang>.json (the same labels as
the /ecosystem/ pages); links are /ecosystem/<slug>/ in English and /<lang>/ecosystem/<slug>/ elsewhere.

  python3 nav_ecosystem.py            sources: index.html + cfo.html (English nav sources), the homepage
                                      and CFO translation files (home/, cfo/), and seo-build/data/chrome-v2.json
  python3 nav_ecosystem.py --built    also patch every already built page that carries the v2 menu, so a
                                      deploy does not need a full rebuild (a later rebuild gives the same menu:
                                      build_lang.py / build_cfo.py turn /ecosystem/ links into /<lang>/ecosystem/)

The /ecosystem/ pages themselves are generated by seo-build/ecosystem.mjs from chrome-v2.json.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
REPO = os.path.dirname(SITE)
LANGS = ['en', 'sk', 'cs', 'de', 'fr', 'es', 'pl', 'hu', 'uk', 'ru']
SLUGS = ['', 'what-is-bitcoin', 'books', 'podcasts', 'videos', 'conferences', 'privacy', 'spend-bitcoin',
         'store-tools', 'dev-tools', 'jobs', 'peers', 'promote']
S = {L: json.load(open(os.path.join(REPO, 'seo-build/data/ecosystem-strings/%s.json' % L), encoding='utf-8')) for L in LANGS}


def nbsp_fr(o):  # French typography, as seo-build/lib/util.mjs nbspFr()
    if isinstance(o, dict):
        return {k: nbsp_fr(v) for k, v in o.items()}
    if isinstance(o, list):
        return [nbsp_fr(v) for v in o]
    return re.sub(r' ([:;?!%»])', '\u00a0\\1', o).replace('« ', '«\u00a0') if isinstance(o, str) else o


S['fr'] = nbsp_fr(S['fr'])


def esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def href(L, slug):
    return '%s/ecosystem/%s' % ('' if L == 'en' else '/' + L, slug + '/' if slug else '')


def page(L, slug):
    return S[L]['pages'][slug or 'index']


def group(L):
    ui = S[L]['ui']
    items = ''.join('<a href="%s"><span class="nd-t">%s</span><span class="nd-d">%s</span></a>' % (
        href(L, s), esc(ui['overview'] if not s else page(L, s)['nav']), esc(page(L, s)['navDesc'])) for s in SLUGS)
    return ('<div class="nav-group" id="ng-eco">\n'
            '        <button type="button" class="nav-group-btn" aria-expanded="false" aria-controls="nd-eco">%s</button>\n'
            '        <div class="nav-drop" id="nd-eco">%s</div>\n'
            '      </div>') % (esc(ui['navLabel']), items)


def column(L):
    ui = S[L]['ui']
    links = ''.join('<a href="%s">%s</a>' % (href(L, s), esc(page(L, s)['h1'] if not s else page(L, s)['nav'])) for s in SLUGS)
    return '<div class="footer-col"><h4>%s</h4>%s</div>' % (esc(ui['navLabel']), links)


def patch(html, L):
    """Insert the group before the About link and the column before the last footer column (Legal)."""
    if '<a class="nav-top"' in html and 'id="ng-eco"' not in html:
        html, n = re.subn(r'(\n[ \t]*)(<a class="nav-top")', lambda m: m.group(1) + group(L) + m.group(1) + m.group(2), html, count=1)
        assert n == 1
    i = html.find('<div class="footer-columns">')
    if i >= 0 and '<h4>%s</h4><a href="%s">' % (esc(S[L]['ui']['navLabel']), href(L, '')) not in html:
        j = html.rfind('<div class="footer-col"><h4>', i, html.find('</footer>', i))
        if j < 0:
            raise SystemExit('footer anchor not found')
        html = html[:j] + column(L) + html[j:]
    return html


def strings(folder):
    """English nav texts -> translations for the homepage / CFO builders (existing keys are kept)."""
    d = os.path.join(HERE, folder)
    en_p = os.path.join(d, 'en_strings.json')
    en = json.load(open(en_p, encoding='utf-8'))
    have = {x['en'] for x in en}

    def texts(L):
        ui = S[L]['ui']
        out = [ui['navLabel'], ui['overview']]
        for s in SLUGS:
            p = page(L, s)
            out += [p['navDesc'], p['h1'] if not s else p['nav']]
        return out
    for k in texts('en'):
        if k not in have:
            en.append({'en': k, 'kind': 'text', 'context': 'Ecosystem menu'})
    open(en_p, 'w', encoding='utf-8').write(json.dumps(en, ensure_ascii=False, indent=1))
    for L in LANGS[1:]:
        p = os.path.join(d, L + '.json')
        tr = json.load(open(p, encoding='utf-8'))
        for k, v in zip(texts('en'), texts(L)):
            if k in tr and tr[k] != v:
                raise SystemExit('%s/%s: "%s" already translated differently' % (folder, L, k))
            tr.setdefault(k, v)
        open(p, 'w', encoding='utf-8').write(json.dumps(tr, ensure_ascii=False, indent=1))


def chrome_json():
    p = os.path.join(REPO, 'seo-build/data/chrome-v2.json')
    c = json.load(open(p, encoding='utf-8'))
    for L in LANGS:
        c[L]['nav'] = patch(c[L]['nav'], L)
        c[L]['foot'] = patch(c[L]['foot'], L)
    open(p, 'w', encoding='utf-8').write(json.dumps(c, ensure_ascii=False, indent=1) + '\n')


def built():
    n = 0
    for root, dirs, files in os.walk(SITE):
        rel = os.path.relpath(root, SITE)
        if rel.startswith(('i18n-tools', 'research', 'brand')) or 'ecosystem' in rel.split(os.sep):
            continue   # the /ecosystem/ pages come from seo-build/ecosystem.mjs
        for f in files:
            if not f.endswith('.html'):
                continue
            p = os.path.join(root, f)
            h = open(p, encoding='utf-8').read()
            if 'id="ng-tools"' not in h or 'id="ng-eco"' in h:
                continue
            L = re.search(r'<html lang="([a-z]{2})', h).group(1)
            open(p, 'w', encoding='utf-8').write(patch(h, L))
            n += 1
    print('built pages patched: %d' % n)


if __name__ == '__main__':
    for f in ('index.html', 'cfo.html'):
        p = os.path.join(SITE, f)
        h = patch(open(p, encoding='utf-8').read(), 'en')
        open(p, 'w', encoding='utf-8').write(h)
    strings('home')
    strings('cfo')
    chrome_json()
    if '--built' in sys.argv:
        built()
    print('Ecosystem menu added to index.html, cfo.html, home/ + cfo/ strings, chrome-v2.json')
