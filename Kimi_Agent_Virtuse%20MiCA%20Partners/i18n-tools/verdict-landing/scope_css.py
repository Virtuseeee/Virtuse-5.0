# -*- coding: utf-8 -*-
"""Scope the approved mockup's CSS under .vl so it never touches the site nav,
footer or the Verdict funnel (.vf) on the same page.
Usage: python3 scope_css.py mockup-approved.html > ../../verdict-landing.css"""
import re, sys

DROP = re.compile(r'(^|[\s,>+~])(\.mk-bar|\.mk-foot|\.vn\b|\.sep\b|\.footer|\.nav\b|\.nav-|\.lang-menu|\.cfo-foot|body:not\(\.stage-wait\)|\.only-wait|\.stage-live)')

def scope_sel(sel):
    sel = sel.strip()
    if not sel: return None
    if DROP.search(' ' + sel): return None
    sel = re.sub(r'^body\.stage-wait\s*', '', sel)
    m = re.match(r'^(html(?:\.anim)?)\s+(.*)$', sel)
    if m:
        if m.group(1) == 'html': return '.vl ' + m.group(2)
        return 'html.anim .vl ' + m.group(2)
    if sel in (':root', 'html', 'body', 'body.stage-wait'): return '.vl'
    if re.match(r'^(:root|html|body)\b', sel): return None
    return '.vl ' + sel

def scope(css):
    out, i, n = [], 0, len(css)
    while i < n:
        if css[i].isspace(): out.append(css[i]); i += 1; continue
        if css.startswith('/*', i):
            j = css.index('*/', i) + 2; i = j; continue
        j = css.index('{', i)
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        body = css[j+1:k-1]
        if head.startswith('@media') or head.startswith('@supports'):
            inner = scope(body)
            if inner.strip(): out.append(head + '{' + inner + '}')
        elif head.startswith('@keyframes') or head.startswith('@font-face') or head.startswith('@'):
            out.append(head + '{' + body + '}')
        else:
            sels = [s for s in (scope_sel(x) for x in head.split(',')) if s]
            if sels: out.append(','.join(sels) + '{' + body.strip() + '}')
        i = k
    return '\n'.join(x for x in out if x.strip())

src = open(sys.argv[1], encoding='utf8').read()
head = src[:src.index('</head>')]
css = '\n'.join(b for a, b in re.findall(r'<style([^>]*)>(.*?)</style>', head, re.S))
print('/* Verdict landing (approved mockup 2026-10-27), scoped under .vl.\n   Generated by i18n-tools/verdict-landing/scope_css.py, do not edit by hand. */')
print(scope(css))
