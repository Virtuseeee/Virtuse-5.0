#!/usr/bin/env python3
"""Page-weight fixes applied to every built page (audit 2026-10-15, code P2-8).

apply(html) runs inside csp_tight.tighten(), so every builder that calls C.finalize() or tighten()
gets it, with no change to the builders themselves:
  - site-v2.css -> site-v2.min.css (generated by i18n-tools/minify_css.py; edit site-v2.css)
  - consultation-widget.js only on pages that have a [data-consultation-trigger] button, and then
    through consultation-lazy.js (loads the 72 KB widget on first hover/focus/touch of a trigger)
  - ONE cache-buster for the shared files on every page (design-align Batch A Part 1, 2026-10-26):
    site-v2.min.css?v=SITE_CSS_V and site-v2.js?v=SITE_JS_V, whatever version a builder wrote.
    Bump these two after any change to site-v2.css / site-v2.js, then run i18n-tools/site_v2_version.py
    (rewrites the pages already built) and seo-build (seo-build/lib/html.mjs imports the same numbers).
"""
import re

SITE_CSS_V = '20'
SITE_JS_V = '12'
CSS_RE = re.compile(r'(href="[^"]*?)site-v2(?:\.min)?\.css\?v=\d+"')
JS_RE = re.compile(r'(src="[^"]*?)site-v2\.js\?v=\d+"')

WIDGET_RE = re.compile(r'[ \t]*<script src="[^"]*consultation-(?:widget|lazy)\.js[^"]*"[^>]*></script>\n?')
EAGER_WIDGET_RE = re.compile(r'<script src="([^"]*?)consultation-widget\.js[^"]*"[^>]*></script>')


def apply(html):
    html = CSS_RE.sub(r'\1site-v2.min.css?v=%s"' % SITE_CSS_V, html)
    html = JS_RE.sub(r'\1site-v2.js?v=%s"' % SITE_JS_V, html)
    if 'data-consultation-trigger' not in html:
        html = WIDGET_RE.sub('', html)
    else:
        html = EAGER_WIDGET_RE.sub(r'<script src="\1consultation-lazy.js?v=1" defer></script>', html)
    return html
