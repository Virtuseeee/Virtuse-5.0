#!/usr/bin/env python3
"""Regenerate the JSON-LD block of news.html (the Virtuse Brief archive) from news/issues.json.

Run it after every new edition (after the entry is added to news/issues.json, and ideally
after the stories build has made /stories/<slug>/):

    python3 seo-ops/news_jsonld.py            # rewrite news.html in place
    python3 seo-ops/news_jsonld.py --check    # exit 1 if news.html is out of date

What it writes, between <!-- news-jsonld:start ... --> and <!-- news-jsonld:end --> in news.html:
  - Organization  @id https://virtuse.com/#org (Virtuse Group, logo email-virtuse-v-mark.png)
  - CollectionPage https://virtuse.com/news.html (mainEntity = the ItemList)
  - ItemList of the editions, newest first. Essays ("essay": true) are left out; they are
    not Brief editions. Each ListItem holds a NewsArticle:
      headline       = issue title
      description    = issue excerpt (em/en dashes replaced)
      datePublished  = issue date
      dateModified   = issue "modified" if present, else the date
      image          = og:image of the static story page, else issue og_image, else image
      url            = https://virtuse.com/stories/<slug>/ if that page exists in the site
                       folder, else https://virtuse.com/article.html?slug=<slug>
      author         = Person Rastislav Vasilisin (about.html#founder)
      publisher      = {"@id": "https://virtuse.com/#org"}
No third-party dependencies. Idempotent.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "Kimi_Agent_Virtuse%20MiCA%20Partners"
NEWS = SITE / "news.html"
ISSUES = SITE / "news" / "issues.json"
BASE = "https://virtuse.com"
ORG_ID = BASE + "/#org"
START = "<!-- news-jsonld:start (generated by seo-ops/news_jsonld.py from news/issues.json; do not edit by hand) -->"
END = "<!-- news-jsonld:end -->"
AUTHOR = {"@type": "Person", "name": "Rastislav Vasilisin", "url": BASE + "/about.html#founder"}


def undash(s):
    s = re.sub(r"(\d)\s*[–—]\s*(\d)", r"\1-\2", s or "")
    s = re.sub(r"\s*[–—]\s*", ", ", s)
    return re.sub(r",\s*([.,;:!?])", r"\1", s).strip(" ,")


def absolute(u):
    if not u:
        return ""
    if u.startswith("http"):
        return u
    return BASE + "/" + u.lstrip("/")


def story_og_image(story):
    m = re.search(r'<meta property="og:image" content="([^"]+)"', story.read_text(encoding="utf-8"))
    return html.unescape(m.group(1)) if m else ""


def build():
    issues = json.loads(ISSUES.read_text(encoding="utf-8")).get("issues", [])
    editions = [i for i in issues if i.get("slug") and i.get("title") and not i.get("essay")]
    editions.sort(key=lambda i: i.get("date", ""), reverse=True)
    items = []
    for pos, i in enumerate(editions, 1):
        slug = i["slug"]
        story = SITE / "stories" / slug / "index.html"
        if story.is_file():
            url = f"{BASE}/stories/{slug}/"
            image = story_og_image(story)
        else:
            url = f"{BASE}/article.html?slug={slug}"
            image = ""
        image = image or absolute(i.get("og_image") or i.get("image") or "")
        art = {
            "@type": "NewsArticle",
            "headline": undash(i["title"]),
            "datePublished": i["date"],
            "dateModified": i.get("modified") or i["date"],
            "url": url,
            "mainEntityOfPage": url,
            "inLanguage": "en",
            "author": AUTHOR,
            "publisher": {"@id": ORG_ID},
        }
        if i.get("excerpt"):
            art["description"] = undash(i["excerpt"])
        if image:
            art["image"] = image
        items.append({"@type": "ListItem", "position": pos, "url": url, "item": art})
    graph = {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "Organization",
                "@id": ORG_ID,
                "name": "Virtuse Group",
                "url": BASE + "/",
                "logo": BASE + "/email-virtuse-v-mark.png",
            },
            {
                "@type": "CollectionPage",
                "@id": BASE + "/news.html#page",
                "url": BASE + "/news.html",
                "name": "Virtuse Brief: weekly Bitcoin newsletter for Europe",
                "inLanguage": "en",
                "publisher": {"@id": ORG_ID},
                "mainEntity": {"@id": BASE + "/news.html#editions"},
            },
            {
                "@type": "ItemList",
                "@id": BASE + "/news.html#editions",
                "name": "Virtuse Brief editions",
                "itemListOrder": "https://schema.org/ItemListOrderDescending",
                "numberOfItems": len(items),
                "itemListElement": items,
            },
        ],
    }
    body = json.dumps(graph, ensure_ascii=False, indent=2)
    return f'{START}\n<script type="application/ld+json">\n{body}\n</script>\n{END}'


def main():
    page = NEWS.read_text(encoding="utf-8")
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if len(pat.findall(page)) != 1:
        sys.exit("news.html: expected exactly one news-jsonld marker pair")
    block = build()
    new = pat.sub(lambda m: block, page)
    if "--check" in sys.argv:
        if new != page:
            sys.exit("news.html JSON-LD is out of date: run python3 seo-ops/news_jsonld.py")
        print("news.html JSON-LD up to date")
        return
    if new != page:
        NEWS.write_text(new, encoding="utf-8")
        print("news.html JSON-LD rewritten")
    else:
        print("news.html JSON-LD unchanged")


if __name__ == "__main__":
    main()
