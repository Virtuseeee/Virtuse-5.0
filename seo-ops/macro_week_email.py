#!/usr/bin/env python3
"""Email section "Macro of the week" / "Makro týždňa" for the Monday Brief (handover A2).

Reads Kimi_Agent_Virtuse%20MiCA%20Partners/news/macro-week.json and writes
email/brief-macro-week-{en,sk}.html: a table fragment in the same style as the
"What else have you missed?" block, to paste into the Brief broadcast HTML, plus
email/brief-macro-week-preview-{en,sk}.html (the fragment in a minimal email
shell) for test sends. A point without source_url is left out. Drafts render too
(for the test send); the page shows the block only when approved is true.

  python3 seo-ops/macro_week_email.py
"""
import html, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "Kimi_Agent_Virtuse%20MiCA%20Partners/news/macro-week.json"
OUT = ROOT / "email"
MONTHS = {"en": "January February March April May June July August September October November December".split(),
          "sk": "januára februára marca apríla mája júna júla augusta septembra októbra novembra decembra".split()}
HEAD = {"en": ("Macro of the week", "The facts that move money this week, with their source. The → BTC line is context, not a recommendation."),
        "sk": ("Makro týždňa", "Fakty, ktoré tento týždeň hýbu peniazmi, so zdrojom. Riadok → BTC je kontext, nie investičné odporúčanie.")}
SERIF = "'Source Serif 4', Georgia, 'Times New Roman', serif"
MONO = "'IBM Plex Mono',ui-monospace,Menlo,Consolas,monospace"

def day(d, lang):
    y, m, dd = d.split("-")
    return f"{int(dd)}. {MONTHS['sk'][int(m)-1]} {y}" if lang == "sk" else f"{int(dd)} {MONTHS['en'][int(m)-1]} {y}"

def fragment(w, lang):
    e = html.escape
    title, dek = HEAD[lang]
    rows = []
    items = [i for i in w["items"] if i.get("source_url")]
    for n, it in enumerate(items):
        fact = it["fact_sk"] if lang == "sk" else it["fact"]
        btc = it["btc_sk"] if lang == "sk" else it["btc"]
        last = n == len(items) - 1
        rows.append(f'''                      <tr>
                        <td bgcolor="#ffffff" style="background-color:#ffffff;padding:12px 0;{'' if last else 'border-bottom:1px solid #e2e0da;'}font-family:{SERIF};font-size:17px;line-height:1.6;color:#16120c;">
                          <strong style="color:#16120c;font-weight:700;">{n+1}.</strong> {e(fact)}<br>
                          <span style="color:#9a5208;font-weight:600;">&rarr; BTC: {e(btc)}</span><br>
                          <a href="{e(it['source_url'])}" target="_blank" style="font-family:{MONO};font-size:12px;color:#5c5c5c;text-decoration:underline;">{e(it['source'])}</a><span style="font-family:{MONO};font-size:12px;color:#5c5c5c;"> &middot; {e(day(it['date'], lang))}</span>
                        </td>
                      </tr>''')
    return f'''          <!-- MACRO OF THE WEEK ({lang}) - generated by seo-ops/macro_week_email.py -->
          <tr>
            <td bgcolor="#ffffff" style="background-color:#ffffff;padding:8px 32px 8px;">
              <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#ffffff" style="background-color:#ffffff;border:1px solid #e2e0da;">
                <tr>
                  <td bgcolor="#ffffff" style="background-color:#ffffff;padding:24px 24px 8px;">
                    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#ffffff" style="background-color:#ffffff;border-bottom:1px solid #16120c;">
                      <tr>
                        <td width="8" valign="middle" style="padding:0 8px 6px 0;">
                          <table role="presentation" cellpadding="0" cellspacing="0" border="0"><tr><td width="6" height="6" bgcolor="#f7931a" style="background-color:#f7931a;font-size:0;line-height:0;width:6px;height:6px;">&nbsp;</td></tr></table>
                        </td>
                        <td valign="middle" style="padding:0 0 6px;font-family:{MONO};font-size:13px;letter-spacing:0.16em;text-transform:uppercase;color:#16120c;font-weight:600;">{e(title)}</td>
                      </tr>
                    </table>
                    <p style="margin:10px 0 0;font-family:{SERIF};font-size:17px;line-height:1.6;color:#5c5c5c;">{e(dek)}</p>
                  </td>
                </tr>
                <tr>
                  <td bgcolor="#ffffff" style="background-color:#ffffff;padding:8px 24px 24px;">
                    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#ffffff" style="background-color:#ffffff;">
{chr(10).join(rows)}
                    </table>
                  </td>
                </tr>
              </table>
            </td>
          </tr>
'''

def preview(frag, lang):
    return f'''<!DOCTYPE html>
<html lang="{lang}"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="color-scheme" content="light only"><title>Virtuse Brief: {HEAD[lang][0]} (test)</title></head>
<body style="margin:0;padding:0;background-color:#f2f0eb;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#f2f0eb" style="background-color:#f2f0eb;">
  <tr><td align="center" style="padding:24px 12px;">
    <table role="presentation" width="640" cellpadding="0" cellspacing="0" border="0" bgcolor="#ffffff" style="width:640px;max-width:100%;background-color:#ffffff;">
      <tr><td style="padding:24px 32px 8px;font-family:{MONO};font-size:12px;letter-spacing:0.12em;text-transform:uppercase;color:#5c5c5c;">Virtuse Brief &middot; {'TEST: sekcia Makro týždňa' if lang == 'sk' else 'TEST: Macro of the week section'}</td></tr>
{frag}      <tr><td style="padding:16px 32px 28px;font-family:{SERIF};font-size:13px;color:#5c5c5c;">{'Testovací e-mail, len pre interné schválenie.' if lang == 'sk' else 'Test email for internal approval only.'}</td></tr>
    </table>
  </td></tr>
</table>
</body></html>
'''

def main():
    w = json.loads(SRC.read_text())
    OUT.mkdir(exist_ok=True)
    for lang in ("en", "sk"):
        frag = fragment(w, lang)
        (OUT / f"brief-macro-week-{lang}.html").write_text(frag)
        (OUT / f"brief-macro-week-preview-{lang}.html").write_text(preview(frag, lang))
    print(f"macro of the week ({w['week']}, approved={w['approved']}): email/brief-macro-week-*.html")

main()
