const hubPathOf = (storyPath) => storyPath.replace(/[^/]+\/$/, '');
const langOfPath = (p) => (p.startsWith('sk/') ? 'sk' : p.startsWith('ru/') ? 'ru' : 'en');
const homeUrl = (lang) => ORIGIN + '/' + (lang === 'en' ? '' : lang + '/');

/** BreadcrumbList for a story: Virtuse > Virtuse Brief > Stories hub > story. */
export function storyCrumbsLd(lang, title, storyPath) {
  const ld = {
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Virtuse', item: homeUrl(lang) },
      { '@type': 'ListItem', position: 2, name: 'Virtuse Brief', item: ORIGIN + '/news.html' },
      { '@type': 'ListItem', position: 3, name: STRINGS[lang].crumb, item: ORIGIN + '/' + hubPathOf(storyPath) },
      { '@type': 'ListItem', position: 4, name: title, item: ORIGIN + '/' + storyPath },
    ],
  };
  return `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>`;
}

function must(h, re, fn, label) {
  if (!re.test(h)) throw new Error('story anchor not found: ' + label);
  return h.replace(re, fn);
}

/**
 * Hub breadcrumb, hub links, BreadcrumbList, related block and asset
 * versions on one story page. Same result whether the page is fresh from
 * the template (build.mjs) or already has them (offline run).
 */
export function applyStoryExtras(html, info, template) {
  const { lang, storyPath } = info;
  const root = '../'.repeat(storyPath.split('/').filter(Boolean).length);
  const hub = root + hubPathOf(storyPath);
  let h = html;
  // ?v= of article.js / article.css as in article.html (asset cache busting).
  for (const f of ['article.js', 'article.css', 'brief-chrome.js']) {
    const re = new RegExp(reEsc(f) + '(\\?v=[^"]*)?"', 'g');
    const m = template.match(new RegExp(reEsc(f) + '(\\?v=[^"]*)?"'));
    if (m) h = h.replace(re, f + (m[1] || '') + '"');
  }
  // Script attributes (defer) as in article.html.
  for (const f of ['lang-detect.js', 'brief-chrome.js', 'article.js']) {
    const m = template.match(new RegExp('<script src="[^"]*' + reEsc(f) + '[^"]*"([^>]*)>'));
    if (m) h = h.replace(new RegExp('(<script src="[^"]*' + reEsc(f) + '[^"]*")[^>]*>', 'g'), (x, a) => a + m[1] + '>');
  }
  // CSP as in article.html (story pages copy the template's head).
  const csp = template.match(/<meta http-equiv="Content-Security-Policy" content="[^"]*">/);
  if (csp) h = h.replace(/<meta http-equiv="Content-Security-Policy" content="[^"]*">/, () => csp[0]);
  h = must(h, /<a href="[^"]*" id="crumbList" data-ui="[^"]*">[^<]*<\/a>/,
    () => `<a href="${hub}" id="crumbList" data-ui="crumbStories">${esc(STRINGS[lang].crumb)}</a>`, 'crumbList');
  h = must(h, /(<a class="text-link" href=")[^"]*(" id="backLink")/, (m, a, b) => a + hub + b, 'backLink');
  h = must(h, /(<a class="text-link" href=")[^"]*(" id="moreAll")/, (m, a, b) => a + hub + b, 'moreAll');
  h = must(h, /<script type="application\/ld\+json">\{"@context":"https:\/\/schema\.org","@type":"BreadcrumbList"[^<]*<\/script>/,
    () => storyCrumbsLd(lang, info.title, storyPath), 'BreadcrumbList');
  const block = relatedHtml(lang, relatedKeys(info), root);
  if (h.includes(REL_START)) {
    h = h.replace(new RegExp(`${reEsc(REL_START)}[\\s\\S]*?${reEsc(REL_END)}`), () => block);
  } else {
    h = must(h, /<div class="story-end">/, () => `${block}\n\n        <div class="story-end">`, 'story-end');
  }
  return h;
}

const attr = (h, re) => { const m = h.match(re); return m ? decode(m[1]) : ''; };

/** What a generated story page says about itself (title, dates, image ...). */
function readStory(storyPath) {
  const file = path.join(SITE, storyPath, 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  const lang = attr(html, /<html lang="([a-z]+)"/) || langOfPath(storyPath);
  const kicker = attr(html, /<p class="story-kicker" id="storyKicker">([^<]*)<\/p>/);
  const deskId = Object.keys(DESK_NAMES[lang] || {}).find((k) => DESK_NAMES[lang][k] === kicker) || '';
  const bodyStart = html.indexOf('<div class="story-body" id="articleBody"');
  const relAt = html.indexOf(REL_START);
  const endAt = relAt > 0 ? relAt : html.indexOf('<div class="story-end">');
  if (bodyStart < 0 || endAt < 0) throw new Error('story body not found: ' + storyPath);
  const bodyHtml = html.slice(html.indexOf('>', bodyStart) + 1, html.lastIndexOf('</div>', endAt));
  const heroTag = /<figure class="story-figure" id="articleHero">/.test(html) ? (html.match(/<img id="heroImg"[^>]*>/) || [''])[0] : '';
  return {
    file, html, lang, storyPath, deskId,
    title: attr(html, /<meta property="og:title" content="([^"]*)"/),
    description: attr(html, /<meta name="description" content="([^"]*)"/),
    published: attr(html, /<meta property="article:published_time" content="([^"]*)"/),
    modified: attr(html, /<meta property="article:modified_time" content="([^"]*)"/),
    bodyText: text(bodyHtml),
    image: heroTag ? {
      src: attr(heroTag, /\ssrc="([^"]*)"/), srcset: attr(heroTag, /\ssrcset="([^"]*)"/),
      width: attr(heroTag, /\swidth="(\d+)"/), height: attr(heroTag, /\sheight="(\d+)"/),
    } : null,
  };
}

