export function buildHubs({ log = console.log } = {}) {
  const template = fs.readFileSync(path.join(SITE, 'article.html'), 'utf8');
  const R = readerLangs();
  const manifest = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')) : {};
  const stories = manifest.stories || [];

  // 1. story pages
  const byLang = {};
  let changed = 0;
  for (const p of stories) {
    if (/^(?:(?:sk|ru)\/)?stories\/page\/$/.test(p)) throw new Error('a story slug "page" would collide with hub pagination: ' + p);
    const s = readStory(p);
    const next = applyStoryExtras(s.html, s, template);
    if (next !== s.html) { fs.writeFileSync(s.file, next); changed++; }
    (byLang[s.lang] = byLang[s.lang] || []).push(s);
  }
  log(`story pages: ${stories.length}, updated ${changed}`);

  // 2. hubs
  const hubLangs = Object.keys(HUB_LANGS).filter((l) => (byLang[l] || []).length);
  const written = [], sitemap = [];
  for (const lang of hubLangs) {
    const list = byLang[lang].sort((a, b) => b.published.localeCompare(a.published) || a.storyPath.localeCompare(b.storyPath));
    const pages = Math.ceil(list.length / PER_PAGE);
    for (let n = 1; n <= pages; n++) {
      const items = list.slice((n - 1) * PER_PAGE, n * PER_PAGE);
      const pg = hubPage(template, R, lang, n, pages, items, (n - 1) * PER_PAGE, list.length, hubLangs);
      const file = path.join(SITE, pg.pagePath, 'index.html');
      fs.mkdirSync(path.dirname(file), { recursive: true });
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== pg.html) fs.writeFileSync(file, pg.html);
      written.push(pg.pagePath);
      sitemap.push(pg);
    }
    log(`${lang} hub: ${list.length} stories, ${pages} page(s)`);
  }

  // Remove hub pages from an earlier run that no longer exist (fewer pages,
  // or a language without stories). Only files this script generated.
  const keep = new Set(written);
  const removed = [];
  for (const p of manifest.hubs || []) {
    if (keep.has(p) || !/^(?:(?:sk|ru)\/)?stories\/(?:page\/\d+\/)?$/.test(p)) continue;
    const file = path.join(SITE, p, 'index.html');
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8').includes(GENERATOR)) {
      fs.rmSync(file);
      if (/page\/\d+\/$/.test(p)) {
        fs.rmSync(path.join(SITE, p), { recursive: true, force: true });
        const pageDir = path.join(SITE, p, '..');
        if (fs.existsSync(pageDir) && !fs.readdirSync(pageDir).length) fs.rmdirSync(pageDir);
      }
      removed.push(p);
    }
  }
  manifest.hubs = written.slice().sort();
  fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');

  // 3. sitemap: our block inside the STORIES-BUILD block.
  const sitemapFile = path.join(SITE, 'sitemap.xml');
  const xml = fs.readFileSync(sitemapFile, 'utf8');
  if (!xml.includes(SITEMAP_START)) throw new Error('sitemap.xml has no STORIES-BUILD block (run build.mjs first)');
  const block = [HUBS_START, ...sitemap.map((pg) => `  <url>
    <loc>${ORIGIN}/${pg.pagePath}</loc>
    <lastmod>${pg.lastmod}</lastmod>${pg.alts.length > 2 ? pg.alts.map(([l, u]) => `
    <xhtml:link rel="alternate" hreflang="${l}" href="${u}"/>`).join('') : ''}
  </url>`), HUBS_END].join('\n');
  let nextXml = xml.replace(new RegExp(`\\n?${reEsc(HUBS_START)}[\\s\\S]*?${reEsc(HUBS_END)}`), '');
  nextXml = nextXml.replace(SITEMAP_START, `${SITEMAP_START}\n${block}`);
  if (nextXml !== xml) fs.writeFileSync(sitemapFile, nextXml);
  log(`sitemap.xml: ${sitemap.length} hub URLs${nextXml === xml ? ' (unchanged)' : ''}`);

  // 4. upload.sftp: hub pages before the sitemap.
  const sftpFile = path.join(HERE, 'upload.sftp');
  if (fs.existsSync(sftpFile)) {
    const dirs = new Set();
    for (const p of written) {
      const parts = p.split('/').filter(Boolean);
      for (let i = 1; i <= parts.length; i++) dirs.add(parts.slice(0, i).join('/'));
    }
    const lines = ['# hubs:start',
      ...[...dirs].filter((d) => d.includes('stories/page'))
        .sort((a, b) => a.split('/').length - b.split('/').length || a.localeCompare(b, 'en', { numeric: true }))
        .map((d) => `-mkdir public_html/${d}`),
      ...written.map((p) => `put ${p}index.html public_html/${p}index.html`),
      ...removed.map((p) => `# removed hub page, delete on the server: public_html/${p}index.html`),
      '# hubs:end'];
    let sftp = fs.readFileSync(sftpFile, 'utf8').replace(/# hubs:start\n[\s\S]*?# hubs:end\n/, '');
    sftp = sftp.includes('put sitemap.xml') ? sftp.replace(/^put sitemap\.xml/m, lines.join('\n') + '\nput sitemap.xml')
      : sftp.replace(/^bye$/m, lines.join('\n') + '\nbye');
    fs.writeFileSync(sftpFile, sftp);
  }
  log(`hubs: ${written.length} pages${removed.length ? `, removed ${removed.length}` : ''}`);
  return { hubs: written, removed, storiesUpdated: changed };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { buildHubs(); } catch (e) { console.error(e); process.exit(1); }
}
