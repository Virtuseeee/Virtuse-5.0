// article.js's LANGS (reader chrome strings), so the hub's nav/footer read in
// the hub's language without loading article.js.
function readerLangs() {
  const src = fs.readFileSync(path.join(SITE, 'article.js'), 'utf8');
  const a = src.indexOf('var LANGS = '), b = src.indexOf('// Pre-rendered /stories/');
  if (a < 0 || b < 0) throw new Error('LANGS not found in article.js');
  return vm.runInNewContext(src.slice(a, b) + '\nLANGS;', {});
}

