function hubPage(template, R, lang, n, pages, items, offset, total, hubLangs) {
  const S = STRINGS[lang], C = HUB_LANGS[lang], L = R[lang] || R.en;
  const pagePath = hubPagePath(lang, n);
  const root = '../'.repeat(pagePath.split('/').filter(Boolean).length);
  const url = ORIGIN + '/' + pagePath;
  const title = n > 1 ? `${S.title}, ${S.page} ${n}` : S.title;
  const description = S.desc(total) + (n > 1 ? ` ${S.Page} ${n} ${S.of} ${pages}.` : '');
  const hubUrl = ORIGIN + '/' + hubPagePath(lang, 1);

  const crumbs = [
    { name: 'Virtuse', item: homeUrl(lang) },
    { name: 'Virtuse Brief', item: ORIGIN + '/news.html' },
    { name: S.crumb, item: hubUrl },
  ];
  if (n > 1) crumbs.push({ name: `${S.Page} ${n}`, item: url });
  const ldPage = {
    '@context': 'https://schema.org', '@type': 'CollectionPage', '@id': url + '#page', url, name: title, description,
    inLanguage: lang,
    isPartOf: { '@type': 'WebSite', name: 'Virtuse', url: ORIGIN + '/' },
    publisher: { '@type': 'Organization', '@id': ORIGIN + '/#org', name: 'Virtuse', url: ORIGIN + '/' },
    mainEntity: {
      '@type': 'ItemList', itemListOrder: 'https://schema.org/ItemListOrderDescending', numberOfItems: items.length,
      itemListElement: items.map((s, i) => ({ '@type': 'ListItem', position: offset + i + 1, url: ORIGIN + '/' + s.storyPath, name: s.title })),
    },
  };
  const ldCrumbs = {
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: crumbs.map((c, i) => ({ '@type': 'ListItem', position: i + 1, name: c.name, item: c.item })),
  };
  const ld = (o) => `<script type="application/ld+json">${JSON.stringify(o).replace(/</g, '\\u003c')}</script>`;
  const alts = n === 1 ? [...hubLangs.map((l) => [l, ORIGIN + '/' + hubPagePath(l, 1)]),
    ['x-default', ORIGIN + '/' + hubPagePath(hubLangs.includes('en') ? 'en' : hubLangs[0], 1)]] : [];
  const head = [
    `<title>${esc(title)} | Virtuse</title>`,
    `<meta name="description" content="${esc(description)}">`,
    `<link rel="canonical" href="${url}">`,
    ...alts.map(([l, u]) => `<link rel="alternate" hreflang="${l}" href="${u}">`),
    n > 1 ? `<link rel="prev" href="${ORIGIN}/${hubPagePath(lang, n - 1)}">` : '',
    n < pages ? `<link rel="next" href="${ORIGIN}/${hubPagePath(lang, n + 1)}">` : '',
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="Virtuse Brief">`,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(description)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${OG_IMAGE.url}">`,
    `<meta property="og:image:width" content="${OG_IMAGE.width}">`,
    `<meta property="og:image:height" content="${OG_IMAGE.height}">`,
    `<meta property="og:locale" content="${C.ogLocale}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${esc(title)}">`,
    `<meta name="twitter:description" content="${esc(description)}">`,
    `<meta name="twitter:image" content="${OG_IMAGE.url}">`,
    ld(ldPage), ld(ldCrumbs),
  ].filter(Boolean).join('\n');

  const cards = items.map((s) => {
    const img = s.image && s.image.src
      ? `<img src="${esc(s.image.src)}"${s.image.srcset ? ` srcset="${esc(s.image.srcset)}" sizes="${CARD_SIZES}"` : ''} alt=""` +
        `${s.image.width ? ` width="${s.image.width}" height="${s.image.height}"` : ''} loading="lazy" decoding="async">`
      : '<div class="blog-card-empty" aria-hidden="true">₿</div>';
    return `        <a class="blog-card" href="${root}${s.storyPath}">${img}<div class="blog-card-body">` +
      `<time datetime="${s.published.slice(0, 10)}">${esc(fmtDate(s.published, lang))}</time><h3>${esc(s.title)}</h3>` +
      `<p class="card-dek">${esc(s.description)}</p><span class="read">${esc(S.read)}</span></div></a>`;
  });
  const pager = [];
  if (pages > 1) {
    if (n > 1) pager.push(`<a class="pg-step" href="${root}${hubPagePath(lang, n - 1)}" rel="prev">${esc(S.newer)}</a>`);
    for (let k = 1; k <= pages; k++) {
      pager.push(k === n ? `<span aria-current="page">${k}</span>` : `<a href="${root}${hubPagePath(lang, k)}" aria-label="${esc(S.Page)} ${k}">${k}</a>`);
    }
    if (n < pages) pager.push(`<a class="pg-step" href="${root}${hubPagePath(lang, n + 1)}" rel="next">${esc(S.older)}</a>`);
  }
  const langNav = hubLangs.map((l) => `<a href="${root}${hubPagePath(l, 1)}" lang="${l}" hreflang="${l}"` +
    `${l === lang ? ' class="on" aria-current="page"' : ''}>${l.toUpperCase()}</a>`).join('\n            ');
  const crumbHtml = `<a href="${root}news.html">Virtuse Brief</a><span class="sep">/</span>` +
    (n > 1 ? `<a href="${root}${hubPagePath(lang, 1)}">${esc(S.crumb)}</a><span class="sep">/</span><span>${esc(S.Page)} ${n}</span>`
      : `<span aria-current="page">${esc(S.crumb)}</span>`);
  const main = `<main id="main">
  <div class="page-inner hub-wrap">
    <nav class="story-crumb" aria-label="Breadcrumb">${crumbHtml}</nav>
    <header class="arch-head">
      <div>
        <p class="arch-kicker">${esc(S.kicker)}</p>
        <h1 class="arch-title">${esc(S.h1)}</h1>
      </div>
      <div class="arch-meta">
        <span><b>${total}</b> ${esc(S.count(total))}</span>
        ${hubLangs.length > 1 ? `<nav class="arch-langs" aria-label="${esc(S.langs)}">
            ${langNav}
        </nav>` : ''}
      </div>
    </header>

    <section class="arch-list" aria-labelledby="gridLabel">
      <div class="section-head"><h2 id="gridLabel">${esc(n > 1 ? `${S.Page} ${n} ${S.of} ${pages}` : S.newest)}</h2></div>
      <div class="blog-grid">
${cards.join('\n')}
      </div>
${pager.length ? `      <nav class="hub-pager" aria-label="${esc(S.pager)}">
        ${pager.join('\n        ')}
      </nav>` : ''}
    </section>
  </div>

  <section class="cap-band" id="subscribe">
    <div class="page-inner cap-inner">
      <div>
        <p class="capture-kicker">${esc(L.ui.capKicker)}</p>
        <p class="capture-dek">${esc(L.ui.capDek)}</p>
      </div>
      <form class="cap-form" id="subscribeForm" novalidate>
        <label class="sr-only" for="capEmail">Email</label>
        <input id="capEmail" type="email" name="email" placeholder="${esc(S.email)}" required autocomplete="email">
        <input type="text" name="website" autocomplete="off" tabindex="-1" aria-hidden="true" class="hp">
        <button class="btn" type="submit">${esc(L.ui.capBtn)}</button>
        <p class="subscribe-msg" id="subscribeMsg" role="status" aria-live="polite"></p>
      </form>
    </div>
  </section>
</main>`;

  let h = template;
  const sub = (re, fn, label) => {
    if (!re.test(h)) throw new Error('article.html anchor not found for hub: ' + label);
    h = h.replace(re, fn);
  };
  // Relative URLs -> this folder depth (same rule as build.mjs render()).
  h = h.replace(/\b(href|src)="(?!https?:|\/|#|data:|mailto:|javascript:)([^"]*)"/g, (m, a, v) => `${a}="${root}${v}"`);
  sub(/<html lang="en" /, () => `<html lang="${lang}" `, 'html');
  sub(/<title>[\s\S]*?<meta name="description"[^>]*>/, () => '<!--HEAD-->', 'title/description');
  h = h.replace(/<link rel="canonical"[^>]*>\n?/g, '');
  h = h.replace(/<meta property="og:[^>]*>\n/g, '').replace(/<meta name="twitter:[^>]*>\n/g, '');
  h = h.replace('<!--HEAD-->', head);
  sub(/<\/head>/, () => `${HUB_CSS}\n${GENERATOR}\n</head>`, '</head>');
  h = h.replace(/<div class="read-progress"[^>]*><\/div>\n/, '');
  sub(/<main id="main">[\s\S]*?<\/main>/, () => main, 'main');
  h = h.replace(/<div class="share-toast"[^>]*><\/div>\n/, '');
  sub(/\n*<!-- ===== Story reader[^>]*-->\n<script src="[^"]*article\.js[^"]*"[^>]*><\/script>/, () => '', 'article.js');
  // Chrome in the hub's language (article.js does this on story pages).
  h = h.replace(/(<([a-z]+)\b[^>]*\bdata-ui="(\w+)"[^>]*>)([^<]*)(<\/\2>)/g, (m, open, tag, key, t, close) =>
    (L.ui[key] != null ? open + esc(L.ui[key]) + close : m));
  h = h.replace(/href="[^"]*"([^>]*?)\sdata-hub="([^"]+)"/g, (m, mid, v) => `href="${root}${L.dir}${v}"${mid}`);
  h = h.replace(/href="[^"]*"(\s+id="(?:navBlog|footBlog)")/g, (m, id) => `href="${root}${L.listPage}"${id}`);
  const ui = {};
  for (const k of ['emailReq', 'sending', 'subOk', 'subErr', 'netErr']) ui[k] = L.ui[k];
  sub(/(<script src="[^"]*brief-chrome\.js[^"]*"[^>]*><\/script>)/, (m) =>
    `<script>window.VB_LANG = ${JSON.stringify(L.worker)}; window.VB_UI = ${JSON.stringify(ui).replace(/</g, '\\u003c')};</script>\n${m}`, 'brief-chrome');
  h = tightenCsp(h, pagePath);
  return { pagePath, html: h, lastmod: items.reduce((a, s) => (s.modified > a ? s.modified : a), '').slice(0, 10), alts };
}

// Per-page CSP for the hubs, same rule as i18n-tools/csp_tight.py (hubs run no
// WordPress HTML, so they are not skipped there): an optional third-party origin
// stays only if a script the page runs mentions it. Keep OPTIONAL in step.
const CSP_OPTIONAL = {
  'script-src': ['https://cdn.jsdelivr.net'],
  'connect-src': ['https://blog.virtuse.com', 'https://api.coingecko.com', 'https://api.binance.com', 'https://mempool.space',
    'https://virtuse-newsletter.virtuse-ai.workers.dev'],
  'frame-src': ['https://widget.firefish.io', 'https://www.youtube.com', 'https://www.youtube-nocookie.com', 'https://open.spotify.com',
    'https://platform.twitter.com', 'https://twitter.com', 'https://x.com'],
};
function tightenCsp(h, pagePath) {
  const csp = /<meta http-equiv="Content-Security-Policy" content="([^"]*)">/;
  const m = h.match(csp);
  if (!m) return h;
  const used = [];
  for (const t of h.matchAll(/<(script|iframe)\b([^>]*)>([\s\S]*?)<\/\1>/gi)) {
    const src = /\bsrc="([^"]*)"/.exec(t[2]);
    if (src) {
      used.push(src[1]);
      if (t[1].toLowerCase() === 'script' && !/^(https?:)?\/\/|^data:/.test(src[1])) {
        const rel = src[1].split(/[?#]/)[0];
        const file = rel.startsWith('/') ? path.join(SITE, rel) : path.join(SITE, pagePath, rel);
        if (fs.existsSync(file)) used.push(fs.readFileSync(file, 'utf8'));
      }
    }
    if (t[1].toLowerCase() === 'script' && !/application\/ld\+json/.test(t[2])) used.push(t[3]);
  }
  const text = used.join('\n');
  const dirs = m[1].split(';').map((d) => d.trim()).filter(Boolean).map((d) => {
    let toks = d.split(/\s+/);
    const opt = CSP_OPTIONAL[toks[0]];
    if (!opt) return d;
    toks = toks.filter((x) => !opt.includes(x));
    for (const o of opt) if (new RegExp('(?<![\\w.-])' + reEsc(o.split('//')[1]) + '(?![\\w-])').test(text)) toks.push(o);
    return toks.join(' ');
  });
  return h.replace(csp, () => `<meta http-equiv="Content-Security-Policy" content="${dirs.join('; ')}">`);
}

