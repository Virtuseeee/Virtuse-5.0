/**
 * Story hubs and story-page extras. Works offline: everything is read from
 * the story pages build.mjs already wrote, so it runs without WordPress.
 *
 *   node stories-build/hubs.mjs        (from the repo root)
 *
 * build.mjs calls buildHubs() at the end of every run, and uses
 * applyStoryExtras() on each page it renders, so a WordPress build and an
 * offline run give the same files.
 *
 * What it does:
 *  1. Story pages (every path in manifest.json): breadcrumb "Stories" pointing
 *     at the language's hub (markup + BreadcrumbList JSON-LD), back/more links
 *     to the hub, and a "Related tools and guides" block (2-3 links to tools and
 *     guides in the story's language, picked from the story's words) between
 *     <!-- STORIES-RELATED:START/END -->. Also keeps the ?v= of article.js /
 *     article.css in step with article.html. Idempotent.
 *  2. Hub pages, newest first, PER_PAGE stories each:
 *       stories/index.html, stories/page/<n>/index.html      (en)
 *       sk/stories/index.html, sk/stories/page/<n>/index.html
 *       ru/stories/index.html, ...
 *     Only for languages that have stories (HUB_LANGS); no hub, and no
 *     hreflang, for any other language. Page 1 hubs list each other in
 *     hreflang (+ x-default = en); later pages are self-canonical only.
 *  3. sitemap.xml: hub URLs between <!-- STORIES-HUBS:START/END -->, inside
 *     build.mjs's STORIES-BUILD block. lastmod = newest story change on that
 *     hub page.
 *  4. upload.sftp: the hub pages between "# hubs:start" / "# hubs:end";
 *     manifest.json "hubs": the generated hub paths (stale pagination pages
 *     are removed on the next run).
 */
